// Regressão pela interface: mesmas ações antes/depois da extração, sem banco.
const boot = require('./harness.js');
const {N,P,L} = boot;
const nodes = [N(1,'pop','ZZ TESTE POP',-20.85,-42.8),N(5,'cto','ZZ TESTE CTO',-20.84,-42.8),N(6,'ceo','ZZ TESTE CEO',-20.83,-42.8)];
const ports = [P(20,5,'fo',1,'Porta 1',1),P(21,5,'fo',2,'Porta 2',1)];
const links = [Object.assign(L(1,'distribuicao',1,5,'ZZ TESTE entrada'),{fiber_count:2}),Object.assign(L(2,'distribuicao',5,6,'ZZ TESTE saída'),{fiber_count:2})];
const {d,w,errs,wait,q,qa,ptr} = boot(()=>({nodes,ports,links}));
let fail = 0;
const ck = (label,condition)=>{ if(!condition) fail++; console.log(condition?'[OK]':'[FALHA]',label); };
const pin = key => ptr(q('[data-pin="'+key+'"]'));
const context = el => el.dispatchEvent(new w.MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:10,clientY:10,button:2}));
(async()=>{
  await wait(300);
  ptr(q('.mnode[data-node="n5"]')); q('#btn-open-diagram').click();
  ck('diagrama abre com cabos, fibras e portas',q('#diagram-overlay').classList.contains('show')&&qa('.dblock').length===3&&qa('[data-pin]').length===6);
  q('#dg-add-splitter').click(); q('#f-spl').value='1x2'; q('#modal-save').click();
  ck('splitter 1x2 adicionado ao diagrama',qa('.spl').length===1&&qa('[data-pin^="splitterPort:"]').length===3);
  pin('fiber:fs1'); pin('splitterPort:sp1-in');
  ck('emenda de entrada usa fusão',q('#toast').textContent==='Emenda criada: fusão.'&&qa('.emenda').length===1);
  pin('splitterPort:sp1-out1'); pin('port:p20');
  ck('saída do splitter usa conector',q('#toast').textContent==='Emenda criada: conectorizada.'&&qa('.emenda').length===2);
  ck('potências preservam perdas históricas',qa('.pwr').map(x=>x.textContent).join('|')==='-18.0|-21.8|-21.8');
  pin('splitterPort:sp1-out1'); pin('port:p21');
  ck('via já ocupada é rejeitada',q('#toast').textContent==='Essa via do splitter já está ocupada.'&&qa('.emenda').length===2);
  q('#dg-role').click(); pin('fiber:fs1');
  ck('técnico destaca o caminho sem criar emenda',qa('.dconn.hl').length===4&&qa('.emenda').length===2&&q('#dg-add-splitter').style.display==='none');
  q('#dg-role').click();
  context(q('.dconn'));
  const passante=qa('#ctxmenu [data-ci]').find(x=>/Passante/.test(x.textContent));
  ck('menu da emenda oferece passante',!!passante);
  passante.click();
  ck('troca da emenda recalcula potência',qa('.pwr').map(x=>x.textContent).join('|')==='-18.0|-21.6|-21.6');
  console.log('snapshot diagrama:',require('crypto').createHash('sha256').update(q('#diagram-svg').innerHTML+q('#diagram-info').innerHTML+q('#diagram-cables').innerHTML).digest('hex'));
  q('#dg-zoom-in').click(); ck('zoom do diagrama funciona',/scale\(1.25\)/.test(q('#dg-root').getAttribute('transform')));
  q('#diagram-back').click(); q('#btn-open-diagram').click();
  ck('reabrir mantém emendas e restaura zoom',qa('.emenda').length===1&&/scale\(1\)/.test(q('#dg-root').getAttribute('transform')));
  q('#diagram-back').click(); q('#btn-edit-node').click(); q('#modal-save').click(); await wait(350);
  ptr(q('.mnode[data-node="n5"]')); q('#btn-open-diagram').click();
  ck('recarga da topologia substitui o estado compartilhado',qa('.spl').length===0&&qa('.dconn').length===0&&qa('.dblock').length===3);
  console.log('falhas:',fail,'| erros console:',errs.length?errs.join('\n '):'nenhum');
  process.exit(fail||errs.length?1:0);
})().catch(error=>{console.error(error);process.exit(1);});
